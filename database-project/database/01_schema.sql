-- BalanceBook 01 스키마와 테이블 생성
-- 실행 위치: balancebook 데이터베이스
-- 시작 상태: acct 스키마가 없음
-- 완료 상태: acct 스키마와 테이블 10개 생성, 모두 0행
-- 근거: Chapter 07 답안 11~12번의 요구사항(P07-MR), 프로젝트 결정(P07-MD), ERD
-- 전체 생성을 하나의 트랜잭션으로 실행합니다.

SELECT current_database();
SELECT current_user;

BEGIN;

DO $$
BEGIN
    IF current_database() <> 'balancebook' THEN
        RAISE EXCEPTION
            '생성 중단: 현재 데이터베이스는 %입니다. balancebook에 연결하세요.',
            current_database();
    END IF;

    IF to_regnamespace('acct') IS NOT NULL THEN
        RAISE EXCEPTION
            '생성 중단: acct 스키마가 이미 있습니다.';
    END IF;
END
$$;

CREATE SCHEMA acct;

-- P07-MR09: 사용자는 이메일과 이름을 가지며, 이메일은 사용자마다 다르다.
CREATE TABLE acct.users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL,
    name VARCHAR(50) NOT NULL,

    CONSTRAINT uq_users_email
        UNIQUE (email)
);

-- P07-MR01: 사업자는 상호와 사업자등록번호를 가진다.
-- 사업자등록번호 중복 금지는 미확정 질문(P07-MQ01)이라 UNIQUE를 두지 않았다.
CREATE TABLE acct.companies (
    company_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    business_no VARCHAR(20) NOT NULL
);

-- P07-MR10: 사용자와 사업자는 N:M이고, 사업자마다 역할을 하나 맡는다.
CREATE TABLE acct.company_users (
    company_user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    role VARCHAR(20) NOT NULL,

    CONSTRAINT fk_company_users_company
        FOREIGN KEY (company_id)
        REFERENCES acct.companies (company_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_company_users_user
        FOREIGN KEY (user_id)
        REFERENCES acct.users (user_id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_company_users_company_user
        UNIQUE (company_id, user_id),

    CONSTRAINT chk_company_users_role
        CHECK (role IN ('대표', '회계 담당자', '검토자'))
);

-- P07-MR12: 같은 사업자의 같은 달 마감 기간은 하나뿐이고, 마감된 기간에는 마감한 사용자가 있다.
CREATE TABLE acct.fiscal_periods (
    period_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL,
    year_month CHAR(7) NOT NULL,
    is_closed BOOLEAN NOT NULL DEFAULT false,
    closed_by INTEGER,

    CONSTRAINT fk_fiscal_periods_company
        FOREIGN KEY (company_id)
        REFERENCES acct.companies (company_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_fiscal_periods_closed_by
        FOREIGN KEY (closed_by)
        REFERENCES acct.users (user_id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_fiscal_periods_company_month
        UNIQUE (company_id, year_month),

    CONSTRAINT chk_fiscal_periods_closed_by
        CHECK (
            (is_closed = true AND closed_by IS NOT NULL)
            OR (is_closed = false AND closed_by IS NULL)
        )
);

-- P07-MR02·MR11, P07-MD01·MD04: 모든 사업자가 함께 쓰는 표준 계정과목.
-- 계정코드는 중복될 수 없고, 계정 분류는 다섯 가지 중 하나다. 상위 계정은 비어 있어도 된다.
CREATE TABLE acct.accounts (
    account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_account_id INTEGER,
    code VARCHAR(10) NOT NULL,
    name VARCHAR(50) NOT NULL,
    account_type VARCHAR(10) NOT NULL,

    CONSTRAINT fk_accounts_parent
        FOREIGN KEY (parent_account_id)
        REFERENCES acct.accounts (account_id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_accounts_code
        UNIQUE (code),

    CONSTRAINT chk_accounts_type
        CHECK (account_type IN ('자산', '부채', '자본', '수익', '비용'))
);

-- P07-MR03: 거래처는 한 사업자에 속하고, 사업자등록번호는 비어 있어도 된다.
CREATE TABLE acct.partners (
    partner_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL,
    name VARCHAR(100) NOT NULL,
    business_no VARCHAR(20),

    CONSTRAINT fk_partners_company
        FOREIGN KEY (company_id)
        REFERENCES acct.companies (company_id)
        ON DELETE RESTRICT
);

-- P07-MR04·MR13, P07-MD02: 전표는 한 사업자에 속하고 작성자를 가진다.
-- 역분개 전표는 원래 전표를 가리키고, 원래 전표 하나는 한 번만 역분개할 수 있다.
CREATE TABLE acct.journal_entries (
    entry_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL,
    created_by INTEGER NOT NULL,
    reversal_of_entry_id INTEGER,
    entry_date DATE NOT NULL,
    description VARCHAR(200) NOT NULL,

    CONSTRAINT fk_journal_entries_company
        FOREIGN KEY (company_id)
        REFERENCES acct.companies (company_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_journal_entries_created_by
        FOREIGN KEY (created_by)
        REFERENCES acct.users (user_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_journal_entries_reversal
        FOREIGN KEY (reversal_of_entry_id)
        REFERENCES acct.journal_entries (entry_id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_journal_entries_reversal
        UNIQUE (reversal_of_entry_id)
);

-- P07-MR05·MR06, P07-MD02: 분개 한 줄은 전표 하나와 계정과목 하나를 가리키고,
-- 차변 또는 대변 중 한쪽에만 0보다 큰 금액이 있다. 거래처는 비어 있어도 된다.
-- 전표 한 장의 차변 합계 = 대변 합계(P07-MR08)는 여러 행에 걸친 규칙이라 여기서 막지 않고,
-- 전표를 저장하는 트랜잭션에서 확인한다(P07-MD03).
CREATE TABLE acct.journal_lines (
    line_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id INTEGER NOT NULL,
    account_id INTEGER NOT NULL,
    partner_id INTEGER,
    debit_amount NUMERIC(12, 0) NOT NULL DEFAULT 0,
    credit_amount NUMERIC(12, 0) NOT NULL DEFAULT 0,

    CONSTRAINT fk_journal_lines_entry
        FOREIGN KEY (entry_id)
        REFERENCES acct.journal_entries (entry_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_journal_lines_account
        FOREIGN KEY (account_id)
        REFERENCES acct.accounts (account_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_journal_lines_partner
        FOREIGN KEY (partner_id)
        REFERENCES acct.partners (partner_id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_journal_lines_one_side
        CHECK (
            (debit_amount > 0 AND credit_amount = 0)
            OR (debit_amount = 0 AND credit_amount > 0)
        )
);

-- P07-MR07: 전표에는 증빙을 0개 이상 연결하고, 증빙은 종류, 발행일, 금액을 가진다.
-- 증빙 금액 CHECK는 수정세금계산서처럼 음수가 있을 수 있어 보류했다.
CREATE TABLE acct.evidences (
    evidence_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id INTEGER NOT NULL,
    evidence_type VARCHAR(30) NOT NULL,
    issue_date DATE NOT NULL,
    amount NUMERIC(12, 0) NOT NULL,

    CONSTRAINT fk_evidences_entry
        FOREIGN KEY (entry_id)
        REFERENCES acct.journal_entries (entry_id)
        ON DELETE RESTRICT
);

-- P07-MR14: 전표를 생성, 수정, 역분개할 때마다 누가 언제 했는지 남긴다.
CREATE TABLE acct.entry_change_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    action VARCHAR(10) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_entry_change_logs_entry
        FOREIGN KEY (entry_id)
        REFERENCES acct.journal_entries (entry_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_entry_change_logs_user
        FOREIGN KEY (user_id)
        REFERENCES acct.users (user_id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_entry_change_logs_action
        CHECK (action IN ('생성', '수정', '역분개'))
);

COMMIT;

